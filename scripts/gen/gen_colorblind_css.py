'''The colour-blind mode's CSS (the owner 2026-10-09: a user can't tell the buff / nerf colours apart; "сделай режим").

Green vs red is the pair red-green colour blindness (about 1 man in 12) merges, and the other tag colours had near
twins too (SWAP teal / MISC grey, REWORK purple / QoL blue). With `html.cb-mode` set (the header switch, remembered
in localStorage) every TAG gets its own colour from CB_TAGS — a set after the Okabe–Ito palette, checked by
simulating deutan / protan eyes (tests/test_colorblind.py: every pair at least MIN_DE apart). Text colours keep
their lightness (readable on the dark rows, the badge says its word anyway); tints and borders move with the tag.
The rest of the site keeps its colours (owner: only tags and dynamics cells).

Generated, not hand-written: the block between the markers (just before the phone block, which stays last) is
rewritten by this script, and tests/test_colorblind.py fails when it is out of date (a new tag rule without its
twin). The dynamics cells read the same colours from scripts.js DYN_TAG_RGB_CB (the test keeps them equal).

    python scripts/gen/gen_colorblind_css.py          # rewrite the block
    python scripts/gen/gen_colorblind_css.py --check  # exit 1 when it is out of date
'''
import colorsys
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSS = os.path.join(ROOT, "styles.css")
BEGIN = "/* === COLOUR-BLIND MODE: generated by scripts/gen/gen_colorblind_css.py — do not edit by hand === */"
END = "/* === END COLOUR-BLIND MODE (generated) === */"
# Each tag's colour now (scripts.js DYN_TAG_RGB) and in the mode (owner 2026-10-09: «перекрасить все теги»).
BASE = {"buff": (93, 177, 78), "new": (220, 175, 95), "rework": (164, 114, 207), "swap": (95, 176, 164),
        "misc": (139, 144, 153), "qol": (108, 171, 240), "del": (177, 78, 107), "nerf": (209, 75, 75)}
CB_TAGS = {"buff": (86, 180, 233), "nerf": (230, 110, 20), "new": (245, 225, 90), "rework": (204, 121, 167),
           "swap": (40, 150, 120), "qol": (40, 80, 170), "del": (120, 40, 70), "misc": (200, 200, 200)}
MIN_DE = 14          # the closest pair (REWORK / SWAP, deutan) — was 1 (BUFF / REWORK) with only buff / nerf swapped
ALPHA_GAIN = 1.5     # a stronger tint behind the badges (owner: «можно поярче, а то тусклые тоже сливаться будут»)
# Which tag a selector paints: the badges, the text-less tag in front of a row, and the numbers («сами цифры
# баффов/нерфов тоже») — % badges are .badge.buffN / nerfN, plus the patch score (.ec-score), the item tooltip and
# recipe cost numbers and the weight line in the dynamics cells (.dyn-wl).
_END = r"(?![\w-])"
TAG_SELECTORS = {
    "buff": re.compile(r'\.badge\.buff|data-tag\*="buff"|\.ec-score\.pos|\.iab-[\w.-]*buff|cost-buff'
                       r'|\.dyn-wl[^,]*\.up' + _END),
    "nerf": re.compile(r'\.badge\.nerf|data-tag\*="nerf"|\.ec-score\.neg|\.iab-[\w.-]*nerf|cost-nerf'
                       r'|\.dyn-wl[^,]*\.down' + _END + r'|^ul\.changes li\.li-notext::before$'),   # its default = NERF
    **{t: re.compile(rf'\.badge\.{t}{_END}|data-tag\*="{t}"') for t in ("new", "rework", "swap", "qol", "del", "misc")},
}
COLOUR = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b|rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)")


def _rgb(m):
    if m.group(1):
        h = m.group(1)
        h = "".join(c * 2 for c in h) if len(h) == 3 else h
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)), None
    return tuple(int(m.group(i)) for i in (2, 3, 4)), m.group(5)


def _hls(rgb):
    return colorsys.rgb_to_hls(*(c / 255 for c in rgb))


def tag_of(selector):
    """The one tag every part of this selector paints, else None (a rule shared by several tags is layout)."""
    tags = set()
    for part in selector.split(","):
        hit = {t for t, rx in TAG_SELECTORS.items() if rx.search(part.strip())}
        if len(hit) != 1:
            return None
        tags |= hit
    return tags.pop() if len(tags) == 1 else None


def recolour(m, tag, text=False):
    """One colour of a `tag` rule in the mode: the tag's hue and saturation; a text colour keeps its lightness, a
    tint / border moves by the tag's lightness step. Shadows and near-white / near-grey colours stay."""
    rgb, alpha = _rgb(m)
    _h, l, s = _hls(rgb)
    if l < 0.08 or l > 0.95 or (s < 0.15 and tag != "misc"):
        return m.group(0)
    th, tl, ts = _hls(CB_TAGS[tag])
    nl = l if text else min(0.88, max(0.12, l + tl - _hls(BASE[tag])[1]))
    r, g, b = (round(c * 255) for c in colorsys.hls_to_rgb(th, nl, ts))
    if alpha is not None:
        return f"rgba({r}, {g}, {b}, {min(1.0, float(alpha) * ALPHA_GAIN):.2f})"
    return f"#{r:02x}{g:02x}{b:02x}" if m.group(1) else f"rgb({r}, {g}, {b})"


def _rules(css):
    """(at-rule prelude or "", selector, body) of every plain rule, with its @media / @supports wrapper."""
    out, stack, i, n = [], [], 0, len(css)
    buf = ""
    while i < n:
        c = css[i]
        if c == "{":
            prelude = " ".join(buf.split())
            buf = ""
            if prelude.startswith("@"):
                stack.append(prelude)
            else:
                j = css.index("}", i)
                body = css[i + 1:j]
                wrap = next((p for p in reversed(stack) if p.startswith(("@media", "@supports"))), "")
                if not any(p.startswith(("@keyframes", "@font-face", "@-webkit-keyframes")) for p in stack):
                    out.append((wrap, prelude, body))
                i = j
        elif c == "}":
            if stack:
                stack.pop()
            buf = ""
        else:
            buf += c
        i += 1
    return out


def _scope(selector):
    parts = []
    for part in selector.split(","):
        part = part.strip()
        if part.startswith(":root"):
            parts.append("html.cb-mode" + part[5:])
        elif part.startswith("html"):
            parts.append("html.cb-mode" + part[4:])
        else:
            parts.append("html.cb-mode " + part)
    return ", ".join(parts)


PHONES = "PHONES (2026-10-05)"   # the phone block must stay last in styles.css (tests/test_phone_css.py)


def build(css):
    """styles.css with the block rewritten: just before the phone block (or at the end without one)."""
    if BEGIN in css:
        i, j = css.index(BEGIN), css.index(END) + len(END)
        css = css[:i].rstrip() + "\n" + css[j:].lstrip("\n")
    source = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    blocks = []
    for wrap, selector, body in _rules(source):
        tag = tag_of(selector)
        if not tag:
            continue
        decls = []
        for d in (d.strip() for d in body.split(";") if d.strip()):
            text = d.split(":", 1)[0].strip() == "color"
            new = COLOUR.sub(lambda m: recolour(m, tag, text), d)
            if new != d:
                decls.append(new)
        if not decls:
            continue
        rule = f"{_scope(selector)} {{ " + "; ".join(decls) + "; }"
        blocks.append(f"{wrap} {{ {rule} }}" if wrap else rule)
    block = BEGIN + "\n" + "\n".join(blocks) + "\n" + END + "\n"
    at = css.rfind("/*", 0, css.index(PHONES)) if PHONES in css else len(css)
    head, tail = css[:at].rstrip() + "\n", css[at:]
    return head + "\n" + block + ("\n" + tail if tail else ""), len(blocks)


def main(argv):
    with open(CSS, encoding="utf-8") as f:
        text = f.read()
    new, n = build(text)
    if "--check" in argv:
        if new != text:
            print("styles.css colour-blind block is out of date: run python scripts/gen/gen_colorblind_css.py")
            return 1
        return 0
    with open(CSS, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print(f"colour-blind block: {n} rules")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
