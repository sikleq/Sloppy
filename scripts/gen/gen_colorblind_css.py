"""The colour-blind mode's CSS (the owner 2026-10-09: a user can't tell the buff / nerf colours apart; "сделай режим").

Green vs red is the pair red-green colour blindness (about 1 man in 12) merges. With `html.cb-mode` set (the header
switch, remembered in localStorage) every BUFF / NERF tag rule (INCLUDE) gets a twin that paints blue instead of
green and orange instead of red — the pair almost every colour vision tells apart. Same lightness; saturation and
the tint's alpha go up (SAT_GAIN, ALPHA_GAIN) so the pair stays bright. The rest of the site keeps its colours (owner: only tags and dynamics cells).

Generated, not hand-written: the block between the markers (just before the phone block, which stays last) is
rewritten by this script, and
tests/test_colorblind.py fails when it is out of date (a new buff / nerf rule without its twin).

    python scripts/gen/gen_colorblind_css.py          # rewrite the block
    python scripts/gen/gen_colorblind_css.py --check  # exit 1 when it is out of date
"""
import colorsys
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSS = os.path.join(ROOT, "styles.css")
BEGIN = "/* === COLOUR-BLIND MODE: generated by scripts/gen/gen_colorblind_css.py — do not edit by hand === */"
END = "/* === END COLOUR-BLIND MODE (generated) === */"
GREEN_HUE, RED_HUE = 200, 30          # → sky blue, orange
# Only the BUFF / NERF tags (owner 2026-10-09: «только для тегов/cells»): the badges, the text-less tag in front of
# a change line and the weight line in the dynamics cells (.dyn-wl). DEL keeps its pink
# (orange would merge it with NERF). The dynamics cells' fill is painted by scripts.js (DYN_TAG_RGB_CB).
# The numbers too («сами цифры баффов/нерфов тоже»): the % badges are .badge.buffN / nerfN already; plus the patch
# score on entity pages (.ec-score) and the buff / nerf numbers in item tooltips and recipe costs.
INCLUDE = re.compile(r'\.badge\.(buff|nerf)|data-tag\*="(buff|nerf)"|\.dyn-wl'
                     r'|\.ec-score\.(pos|neg)|\.iab-[\w.-]*(buff|nerf)|cost-(buff|nerf)')
# Brighter than a plain hue swap (owner: «можно поярче, а то тусклые тоже сливаться будут»): more saturation, a
# stronger tint behind the badges.
SAT_GAIN, SAT_ADD, ALPHA_GAIN = 1.3, 0.12, 1.5
COLOUR = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b|rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)")


def _rgb(m):
    if m.group(1):
        h = m.group(1)
        h = "".join(c * 2 for c in h) if len(h) == 3 else h
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)), None
    return tuple(int(m.group(i)) for i in (2, 3, 4)), m.group(5)


def kind(rgb):
    """'green' / 'red' for a saturated green or red, else None."""
    h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in rgb))
    deg = h * 360
    if s < 0.22 or l < 0.12 or l > 0.93:
        return None
    if 80 <= deg <= 165:
        return "green"
    if deg <= 18 or deg >= 340:
        return "red"
    return None


def remap(m):
    rgb, alpha = _rgb(m)
    k = kind(rgb)
    if not k:
        return m.group(0)
    _h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in rgb))
    s = min(1.0, s * SAT_GAIN + SAT_ADD)
    r, g, b = (round(c * 255) for c in colorsys.hls_to_rgb((GREEN_HUE if k == "green" else RED_HUE) / 360, l, s))
    if alpha is not None:
        return f"rgba({r}, {g}, {b}, {min(1.0, float(alpha) * ALPHA_GAIN):.2f})"
    return f"#{r:02x}{g:02x}{b:02x}" if m.group(1) else f"rgb({r}, {g}, {b})"


def _rules(css):
    """(at-rule prelude or "", selector, body) of every plain rule, with its @media / @supports wrapper."""
    out, stack, i, n = [], [], 0, len(css)
    buf = ""
    while i < n:
        c = css[i]
        if c == "{":
            prelude = " ".join(buf.split())
            buf = ""
            if prelude.startswith("@"):
                stack.append(prelude)
            else:
                j = css.index("}", i)
                body = css[i + 1:j]
                wrap = next((p for p in reversed(stack) if p.startswith(("@media", "@supports"))), "")
                if not any(p.startswith(("@keyframes", "@font-face", "@-webkit-keyframes")) for p in stack):
                    out.append((wrap, prelude, body))
                i = j
        elif c == "}":
            if stack:
                stack.pop()
            buf = ""
        else:
            buf += c
        i += 1
    return out


def _scope(selector):
    parts = []
    for part in selector.split(","):
        part = part.strip()
        if part.startswith(":root"):
            parts.append("html.cb-mode" + part[5:])
        elif part.startswith("html"):
            parts.append("html.cb-mode" + part[4:])
        else:
            parts.append("html.cb-mode " + part)
    return ", ".join(parts)


PHONES = "PHONES (2026-10-05)"   # the phone block must stay last in styles.css (tests/test_phone_css.py)


def build(css):
    """styles.css with the block rewritten: just before the phone block (or at the end without one)."""
    if BEGIN in css:
        i, j = css.index(BEGIN), css.index(END) + len(END)
        css = css[:i].rstrip() + "\n" + css[j:].lstrip("\n")
    source = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    blocks = []
    for wrap, selector, body in _rules(source):
        if not INCLUDE.search(selector):
            continue
        decls = [d.strip() for d in body.split(";") if d.strip()]
        hot = [d for d in decls if any(kind(_rgb(m)[0]) for m in COLOUR.finditer(d))]
        if not hot:
            continue
        rule = f"{_scope(selector)} {{ " + "; ".join(COLOUR.sub(remap, d) for d in hot) + "; }"
        blocks.append(f"{wrap} {{ {rule} }}" if wrap else rule)
    block = BEGIN + "\n" + "\n".join(blocks) + "\n" + END + "\n"
    at = css.rfind("/*", 0, css.index(PHONES)) if PHONES in css else len(css)
    head, tail = css[:at].rstrip() + "\n", css[at:]
    return head + "\n" + block + ("\n" + tail if tail else ""), len(blocks)


def main(argv):
    with open(CSS, encoding="utf-8") as f:
        text = f.read()
    new, n = build(text)
    if "--check" in argv:
        if new != text:
            print("styles.css colour-blind block is out of date: run python scripts/gen/gen_colorblind_css.py")
            return 1
        return 0
    with open(CSS, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print(f"colour-blind block: {n} rules")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
